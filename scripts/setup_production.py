def _parse_env(content: str) -> dict[str, str]:
    """Parse KEY=value lines (comments and blanks skipped; last assignment wins)."""
    values: dict[str, str] = {}
    for raw in content.splitlines():
        line = raw.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        values[key.strip()] = value.strip().strip('"').strip("'")
    return values


def _is_placeholder(value: str) -> bool:
    return (
        not value
        or value.startswith(PLACEHOLDER_PREFIXES)
        or value.startswith("REPLACE")
        or PLACEHOLDER_DOMAIN in value
    )


def validate_env_file(env_path: Path) -> bool:
    """Validate that the .env file has required production settings."""
    if not env_path.exists():
        print(f"ERROR: .env file not found at {env_path}")
        return False

    with open(env_path, encoding="utf-8") as f:
        values = _parse_env(f.read())

    issues = []
    warnings = []

    # Always required. The app refuses to start in production without these.
    for var in ("SECRET_KEY", "ENCRYPTION_SALT", "AUDIT_HMAC_KEY"):
        value = values.get(var, "")
        if var not in values:
            issues.append(f"Missing required variable: {var}")
        elif _is_placeholder(value):
            issues.append(f"{var} has placeholder value - needs real value")
        elif var != "ENCRYPTION_SALT" and len(value) < 32:
            issues.append(f"{var} is too short - needs 32+ characters")

    # Database / Redis: either the URL itself, or the password the bundled
    # docker-compose.prod.yml builds the URL from.
    for url_var, password_var in (
        ("DATABASE_URL", "POSTGRES_PASSWORD"),
        ("REDIS_URL", "REDIS_PASSWORD"),
    ):
        url, password = values.get(url_var, ""), values.get(password_var, "")
        if _is_placeholder(url) and _is_placeholder(password):
            issues.append(
                f"Set {password_var} (bundled docker-compose.prod.yml) or {url_var} "
                "(external service)"
            )

    # Hostname: DOMAIN (bundled stack derives CORS_ORIGINS/ALLOWED_HOSTS from it)
    # or both set explicitly (docker-compose.yml / bare metal).
    domain = values.get("DOMAIN", "")
    if _is_placeholder(domain):
        for var in ("CORS_ORIGINS", "ALLOWED_HOSTS"):
            if _is_placeholder(values.get(var, "")):
                issues.append(f"{var} is not set (or set DOMAIN for the bundled stack)")
    for var in ("DOMAIN", "CORS_ORIGINS", "ALLOWED_HOSTS", "FRONTEND_URL"):
        if PLACEHOLDER_DOMAIN in values.get(var, ""):
            issues.append(f"{var} still contains the placeholder '{PLACEHOLDER_DOMAIN}'")

    if values.get("DISK_ENCRYPTION_ACKNOWLEDGED", "").lower() != "true":
        issues.append(
            "DISK_ENCRYPTION_ACKNOWLEDGED is not true - encrypt the data volumes, "
            "then set it to true (the app refuses to start otherwise)"
        )

    if values.get("DEBUG", "").lower() == "true":
        issues.append("DEBUG is enabled - must be false for production")

    # Advisory only: a server-level provider key is optional (BYOK).
    if all(_is_placeholder(values.get(var, "")) for var in ("OPENAI_API_KEY", "ANTHROPIC_API_KEY")):
        warnings.append(
            "No server-level AI provider key - fine for bring-your-own-key, but each "
            "user must save their own key under Settings before anything works"
        )
    for var in ("OPENAI_API_KEY", "ANTHROPIC_API_KEY", "VOYAGE_API_KEY", "COHERE_API_KEY"):
        value = values.get(var, "")
        if value and _is_placeholder(value):
            issues.append(f"{var} has placeholder value - set a real key or leave it empty")
    if not values.get("REGISTRATION_BOOTSTRAP_TOKEN"):
        warnings.append(
            "REGISTRATION_BOOTSTRAP_TOKEN is not set - on a fresh instance the first "
            "(admin) account cannot be registered without it"
        )
    if values.get("BACKUP_ENCRYPTION_KEY"):
        warnings.append(
            "BACKUP_ENCRYPTION_KEY is in this file - keep it off this server (supply "
            "it in the backup job's environment instead)"
        )

    # Print results
    print("\n" + "=" * 60)
    print("ENVIRONMENT VALIDATION RESULTS")
    print("=" * 60)

    if issues:
        print("\n[FAIL] ISSUES FOUND (must fix):")
        for issue in issues:
            print(f"   - {issue}")

    if warnings:
        print("\n[WARN] WARNINGS:")
        for warning in warnings:
            print(f"   - {warning}")

    if not issues and not warnings:
        print("\n[OK] All validation checks passed!")
    elif not issues:
        print("\n[OK] No blocking issues.")

    print("=" * 60 + "\n")

    return len(issues) == 0


def main():
    parser = argparse.ArgumentParser(
        description="Production setup and secret generation for CaseCite"
    )
    parser.add_argument(
        "--generate-secrets",
        action="store_true",
        help="Generate new cryptographic secrets",
    )
    parser.add_argument(
        "--create-env",
        action="store_true",
        help="Create the .env file (refuses to overwrite an existing one)",
    )
    parser.add_argument(
        "--domain",
        type=str,
        default=PLACEHOLDER_DOMAIN,
        help="With --create-env: the public hostname (e.g. app.example.com)",
    )
    parser.add_argument(
        "--disk-encrypted",
        action="store_true",
        help="With --create-env: set DISK_ENCRYPTION_ACKNOWLEDGED=true "
        "(only if the data volumes are on an encrypted disk)",
    )
    parser.add_argument(
        "--validate", action="store_true", help="Validate existing .env configuration"
    )
    parser.add_argument(
        "--env-file",
        type=str,
        default=".env",
        help="Path to the .env file, relative to the repository root (default: .env)",
    )

    args = parser.parse_args()

    if not any([args.generate_secrets, args.create_env, args.validate]):
        parser.print_help()
        print("\nExamples:")
        print("  python3 scripts/setup_production.py --generate-secrets")
        print("  python3 scripts/setup_production.py --create-env --domain app.example.com")
        print("  python3 scripts/setup_production.py --validate")
        sys.exit(1)

    project_root = Path(__file__).resolve().parent.parent
    env_path = Path(args.env_file)
    if not env_path.is_absolute():
        env_path = project_root / env_path

    if args.generate_secrets:
        print_secrets()

    if args.create_env:
        if env_path.exists():
            print(f"ERROR: {env_path} already exists - refusing to overwrite it.")
            print("       Its SECRET_KEY/ENCRYPTION_SALT may protect existing data.")
            print("       Pass --env-file <other-name> to write somewhere else.")
            sys.exit(1)
        env_content = create_env_template(args.domain, args.disk_encrypted)
        # Owner read/write only from the moment the file exists (no-op on Windows).
        fd = os.open(env_path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
        with os.fdopen(fd, "w", encoding="utf-8") as f:
            f.write(env_content)
        print(f"\n[OK] Created {env_path} (mode 0600)")
        if args.domain == PLACEHOLDER_DOMAIN:
            print(f"   Replace '{PLACEHOLDER_DOMAIN}' with your hostname")
        if not args.disk_encrypted:
            print("   Set DISK_ENCRYPTION_ACKNOWLEDGED=true once the volumes are encrypted")
        print("   Then run: python3 scripts/setup_production.py --validate")
        print("   IMPORTANT: Keep a secure backup of the generated secrets!\n")

    if args.validate:
        success = validate_env_file(env_path)
        sys.exit(0 if success else 1)


if __name__ == "__main__":
    main()
