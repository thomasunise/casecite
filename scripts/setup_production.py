#!/usr/bin/env python3
"""
Production Setup Script for CaseCite

This script helps generate production secrets securely.
Run this script to:
1. Generate new cryptographic secrets
2. Create a .env file with secure values
3. Validate existing configuration

Usage:
    python3 scripts/setup_production.py --generate-secrets
    python3 scripts/setup_production.py --create-env --domain app.example.com
    python3 scripts/setup_production.py --validate

Rotating ENCRYPTION_SALT is a separate tool (scripts/rotate_encryption_key.py);
SECRET_KEY cannot be rotated in place — see docs/secret-rotation.md.
"""

import argparse
import os
import secrets
import sys
from pathlib import Path

# Mirrors _PLACEHOLDER_PREFIXES in backend/app/config.py, plus the values this
# script and .env.example use for "fill this in".
PLACEHOLDER_PREFIXES = ("change-me", "REPLACE_WITH", "REPLACE-ME", "your-", "sk-your")
PLACEHOLDER_DOMAIN = "your-domain.com"


def generate_secret_key() -> str:
    """Generate a cryptographically secure secret key (64 hex chars = 32 bytes)."""
    return secrets.token_hex(32)


def generate_encryption_salt() -> str:
    """Generate a cryptographically secure encryption salt (32 hex chars = 16 bytes)."""
    return secrets.token_hex(16)


def print_secrets():
    """Generate and print new secrets."""
    print("\n" + "=" * 60)
    print("GENERATED PRODUCTION SECRETS")
    print("=" * 60)
    print("\nCopy these values to your .env file or secrets manager:\n")
    print(f"SECRET_KEY={generate_secret_key()}")
    print(f"ENCRYPTION_SALT={generate_encryption_salt()}")
    print(f"AUDIT_HMAC_KEY={generate_secret_key()}")
    print(f"POSTGRES_PASSWORD={generate_secret_key()}")
    print(f"REDIS_PASSWORD={generate_secret_key()}")
    print("\n" + "=" * 60)
    print("IMPORTANT SECURITY NOTES:")
    print("=" * 60)
    print("1. Never commit these values to git")
    print("2. Use a secrets manager in production (AWS Secrets Manager, Azure Key Vault)")
    print("3. Never change SECRET_KEY or ENCRYPTION_SALT after first run without")
    print("   following docs/secret-rotation.md — encrypted data becomes unreadable")
    print("4. Keep a copy of SECRET_KEY, ENCRYPTION_SALT and AUDIT_HMAC_KEY off the")
    print("   server: backups cannot be restored without them")
    print("=" * 60 + "\n")


