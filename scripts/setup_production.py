def validate_env_file(env_path: Path) -> bool:
    """Validate that the .env file has required production settings."""
    if not env_path.exists():
        print(f"ERROR: .env file not found at {env_path}")
        return False

    with open(env_path) as f:
        content = f.read()

    required_vars = [
        "SECRET_KEY",
        "ENCRYPTION_SALT",
        "DATABASE_URL",
        "REDIS_URL",
        "OPENAI_API_KEY",
        "CORS_ORIGINS",
    ]

    issues = []
    warnings = []

    for var in required_vars:
        if f"{var}=" not in content:
            issues.append(f"Missing required variable: {var}")
        else:
            # Check for placeholder values
            for line in content.split("\n"):
                if line.startswith(f"{var}="):
                    value = line.split("=", 1)[1].strip()
                    if not value or value.startswith("REPLACE") or value == "your-key-here":
                        issues.append(f"{var} has placeholder value - needs real value")
                    elif var == "SECRET_KEY" and len(value) < 32:
                        issues.append(f"{var} is too short - needs 32+ characters")

    # Check for debug mode
    for line in content.split("\n"):
        if line.startswith("DEBUG=true") or line.startswith("DEBUG=True"):
            warnings.append("DEBUG is enabled - should be false for production")

    # Print results
    print("\n" + "=" * 60)
    print("ENVIRONMENT VALIDATION RESULTS")
    print("=" * 60)

    if issues:
        print("\n❌ ISSUES FOUND (must fix):")
        for issue in issues:
            print(f"   - {issue}")

    if warnings:
        print("\n⚠️  WARNINGS:")
        for warning in warnings:
            print(f"   - {warning}")

    if not issues and not warnings:
        print("\n✅ All validation checks passed!")

    print("=" * 60 + "\n")

    return len(issues) == 0


def main():
    parser = argparse.ArgumentParser(description="Production setup and secret management for CaseCite")
    parser.add_argument(
        "--generate-secrets",
        action="store_true",
        help="Generate new cryptographic secrets",
    )
    parser.add_argument(
        "--create-env",
        action="store_true",
        help="Create a new .env.production template file",
    )
    parser.add_argument(
        "--validate", action="store_true", help="Validate existing .env configuration"
    )
    parser.add_argument(
        "--env-file", type=str, default=".env", help="Path to .env file (default: .env)"
    )

    args = parser.parse_args()

    if not any([args.generate_secrets, args.create_env, args.validate]):
        parser.print_help()
        print("\nExamples:")
        print("  python scripts/setup_production.py --generate-secrets")
        print("  python scripts/setup_production.py --create-env")
        print("  python scripts/setup_production.py --validate")
        sys.exit(1)

    if args.generate_secrets:
        print_secrets()

    if args.create_env:
        output_path = Path(args.env_file + ".production")
        env_content = create_env_template()
        with open(output_path, "w") as f:
            f.write(env_content)
        print(f"\n✅ Created {output_path}")
        print("   Review and rename to .env for production use")
        print("   IMPORTANT: Keep a secure backup of the generated secrets!\n")

    if args.validate:
        # Find project root
        script_dir = Path(__file__).parent
        project_root = script_dir.parent
        env_path = project_root / args.env_file
        success = validate_env_file(env_path)
        sys.exit(0 if success else 1)


if __name__ == "__main__":
    main()
