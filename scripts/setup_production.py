#!/usr/bin/env python3
"""
Production Setup Script for CaseCite

This script helps generate and rotate production secrets securely.
Run this script to:
1. Generate new cryptographic secrets
2. Create a .env file template with secure values
3. Validate existing configuration

Usage:
    python scripts/setup_production.py --generate-secrets
    python scripts/setup_production.py --validate
    python scripts/setup_production.py --rotate-secret-key
"""

import argparse
import secrets
import sys
from pathlib import Path


def generate_secret_key() -> str:
    """Generate a cryptographically secure secret key (64 hex chars = 32 bytes)."""
    return secrets.token_hex(32)


def generate_encryption_salt() -> str:
    """Generate a cryptographically secure encryption salt (32 hex chars = 16 bytes)."""
    return secrets.token_hex(16)


def generate_api_key_placeholder() -> str:
    """Generate a placeholder for API keys."""
    return f"REPLACE_ME_{secrets.token_hex(8).upper()}"


def print_secrets():
    """Generate and print new secrets."""
    print("\n" + "=" * 60)
    print("GENERATED PRODUCTION SECRETS")
    print("=" * 60)
    print("\nCopy these values to your .env file or secrets manager:\n")
    print(f"SECRET_KEY={generate_secret_key()}")
    print(f"ENCRYPTION_SALT={generate_encryption_salt()}")
    print("\n" + "=" * 60)
    print("IMPORTANT SECURITY NOTES:")
    print("=" * 60)
    print("1. Never commit these values to git")
    print("2. Use a secrets manager in production (AWS Secrets Manager, Azure Key Vault)")
    print("3. Rotate encryption keys: python scripts/rotate_encryption_key.py")
    print("4. Keep backups of secrets in a secure location")
    print("=" * 60 + "\n")


